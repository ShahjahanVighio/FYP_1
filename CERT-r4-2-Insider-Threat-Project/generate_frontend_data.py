# 2. Load feature rankings
df_rankings = pd.read_csv("prepared_data/feature_rankings_all.csv")
with open("prepared_data/selected_features.json", "r") as f:
    selected_50 = json.load(f)

# Filter top 50 in order
df_top50 = df_rankings[df_rankings['Feature'].isin(selected_50)].copy()
df_top50 = df_top50.sort_values(by="Combined_Rank").reset_index(drop=True)

def tag_feature(feat):
    if "usb" in feat.lower():
        return "Removable Media / USB"
    elif "leak" in feat.lower():
        return "Data Leak Sites / Cloud"
    elif "job" in feat.lower():
        return "Job Search Activity"
    elif "hack" in feat.lower():
        return "Hacking / Keylogger"
    elif "file" in feat.lower():
        return "File Exfiltration"
    elif feat in ["O", "C", "E", "A", "N"]:
        return "Psychometric (OCEAN)"
    elif feat in ["role", "dept", "team", "business_unit", "functional_unit"]:
        return "Organizational / LDAP"
    else:
        return "Temporal & Session Dynamics"

features_list = []
for _, row in df_top50.iterrows():
    f_name = row['Feature']
    features_list.append({
        "name": f_name,
        "category": tag_feature(f_name),
        "anova_f": float(row['ANOVA_F']),
        "mi": float(row['MI']),
        "anova_rank": int(row['ANOVA_Rank']),
        "mi_rank": int(row['MI_Rank']),
        "combined_rank": float(row['Combined_Rank'])
    })

# 3. Calculate distributions for top features for simulator sliders
X_train_raw = pd.read_parquet("prepared_data/X_train_raw.parquet")
feature_stats = {}
for col in selected_50:
    s = X_train_raw[col]
    feature_stats[col] = {
        "min": float(s.min()),
        "p25": float(s.quantile(0.25)),
        "median": float(s.median()),
        "p75": float(s.quantile(0.75)),
        "p95": float(s.quantile(0.95)),
        "max": float(s.max()),
        "mean": float(s.mean()),
        "std": float(s.std())
    }

